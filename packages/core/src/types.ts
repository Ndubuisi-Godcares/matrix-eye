/**
 * Domain types shared by every Eagle's Eye package.
 *
 * These describe the data that flows through the pipeline:
 *   website -> CrawledPage -> Chunk -> SearchHit -> ChatResponse (with Citations)
 */

/** A heading-delimited block of text from a page. `headingPath` is the chain of headings above it. */
export interface PageSection {
  headingPath: string[];
  text: string;
}

/** A single web page after fetching and boilerplate removal. */
export interface CrawledPage {
  /** The URL that was requested (after normalisation). */
  url: string;
  /** The page's declared canonical URL if present, else `url`. Used for de-duplication. */
  canonicalUrl: string;
  title: string;
  description: string;
  /** Main content split by headings. */
  sections: PageSection[];
  /** Flattened main-content text, used for hashing and language-model-free fallbacks. */
  text: string;
  /** SHA-256 of `text`; lets re-crawls skip unchanged pages. */
  contentHash: string;
  /** ISO timestamp. */
  fetchedAt: string;
}

/** A retrievable passage of a page. This is the unit that is indexed and cited. */
export interface Chunk {
  /** Deterministic id derived from page URL, position and text. */
  id: string;
  pageUrl: string;
  pageTitle: string;
  headingPath: string[];
  text: string;
  /** Zero-based order of the chunk within its page. */
  position: number;
}

/** A chunk returned by retrieval. `score` is higher-is-better and always positive. */
export interface SearchHit {
  chunk: Chunk;
  score: number;
}

/** A source shown to the visitor next to an answer. */
export interface Citation {
  /** 1-based number the answer text refers to, e.g. "[1]". */
  id: number;
  url: string;
  title: string;
  /** Short excerpt of the supporting passage. */
  snippet: string;
}

export type ChatRole = "user" | "assistant";

/** One prior turn of a conversation, supplied by the caller for follow-up handling. */
export interface ChatTurn {
  role: ChatRole;
  content: string;
}

/**
 * How an answer was produced. Useful for analytics and for trusting an answer appropriately:
 *  - `rule`        a configured deterministic rule fired
 *  - `facts`       answered from extracted structured facts (contact details)
 *  - `smalltalk`   a greeting, thanks or goodbye
 *  - `overview`    "what is this site about?" answered from the front page's own description
 *  - `llm`         generated by the language model from retrieved evidence
 *  - `extractive`  composed directly from retrieved passages (no model, or model fallback)
 *  - `abstain`     evidence was insufficient, so the assistant declined to answer
 */
export type AnswerRoute = "rule" | "facts" | "smalltalk" | "overview" | "llm" | "extractive" | "abstain";

export interface ChatResponse {
  answer: string;
  abstained: boolean;
  route: AnswerRoute;
  citations: Citation[];
  /** Diagnostic detail for dashboards and the evaluation harness. Safe to omit from public responses. */
  debug?: ChatDebug;
}

export interface ChatDebug {
  rewrittenQuery: string;
  hitCount: number;
  topScore: number;
  /** Fraction (0..1) of the question's content words found in the retrieved evidence. */
  coverage: number;
  /** Validation problems the answer had before it was repaired or replaced. */
  issues: string[];
  timingsMs: Record<string, number>;
}

/** A configured deterministic rule that overrides generation (prices, policies, canned replies). */
export interface Rule {
  id: string;
  /** Higher priority rules are evaluated first. */
  priority: number;
  /** Rule fires when ALL of these words appear in the question (case-insensitive, whole word). */
  allOf?: string[];
  /** ...and at least ONE of these appears (when provided). */
  anyOf?: string[];
  /** Alternatively, a regular expression source tested against the question. */
  pattern?: string;
  /** The fixed answer returned when the rule fires. */
  response: string;
}

/** A structured fact extracted from the website during ingestion. */
export interface Fact {
  kind: "email" | "phone";
  value: string;
  /** Page the fact was found on, so the answer can cite it. */
  pageUrl: string;
  pageTitle: string;
}
